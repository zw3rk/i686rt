#!/usr/bin/env python3
"""Generate the i386 syscall table header for i686rt (Phase 1, L1f).

Fetches the kernel's ``arch/x86/entry/syscalls/syscall_32.tbl`` — the
single source of truth for 32-bit x86 (int 0x80) syscall numbers — and
emits ``src/os/syscalls_i386.h`` with a designated-initializer table plus
``I686__NR_*`` macros for the set implemented by ``src/os/syscalls.c``.

Usage:
    python3 tools/gen_syscall_tab.py [output-path]

Sources are tried in order (first that answers wins):
    1. $I686RT_SYSCALL_TBL — local file override for hermetic runs
    2. torvalds/linux master syscall_32.tbl
    3. torvalds/linux v6.12 syscall_32.tbl (stable-tag fallback)

The output is deterministic (no timestamps), so regeneration is
idempotent.  stdlib only.
"""

# Copyright 2026 Moritz Angermann <moritz@zw3rk.com>, zw3rk pte. ltd.
# SPDX-License-Identifier: Apache-2.0

import os
import re
import sys
import urllib.request

MASTER_URL = (
    "https://raw.githubusercontent.com/torvalds/linux/master/"
    "arch/x86/entry/syscalls/syscall_32.tbl"
)
V612_URL = (
    "https://raw.githubusercontent.com/torvalds/linux/v6.12/"
    "arch/x86/entry/syscalls/syscall_32.tbl"
)

GUARD = "I686RT_OS_SYSCALLS_I386_H"

# Sanity window for syscall numbers: the real table spans 0..472 today;
# anything outside [0, NR_LIMIT) means we parsed garbage, not a table.
NR_LIMIT = 4096

NAME_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z")

# Syscalls implemented by src/os/syscalls.c in Phase 1.  The generator
# cross-checks every nr against the parsed table and refuses to emit on
# drift, so the macros can never lie about the kernel's numbering.
IMPLEMENTED = {
    "exit": 1,
    "read": 3,
    "write": 4,
    "getpid": 20,
    "brk": 45,
    "uname": 122,
    "mmap2": 192,
    "set_thread_area": 243,
    "exit_group": 252,
}


def die(msg):
    sys.stderr.write("gen_syscall_tab: %s\n" % msg)
    sys.exit(1)


def fetch_url(url):
    req = urllib.request.Request(
        url, headers={"User-Agent": "i686rt-gen-syscall-tab/1.0"}
    )
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read().decode("utf-8")


def fetch_local(path):
    with open(path, "r", encoding="utf-8") as fh:
        return fh.read()


def parse_tbl(text, source):
    """Parse '<nr> <abi> <name> [entry points...]' lines.

    Comment (#) and blank lines are skipped; every numbered row of the
    i386 table counts regardless of its abi token (i386/x32/common).
    Returns {nr: name}.
    """
    table = {}
    for lineno, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        fields = line.split()
        if len(fields) < 3:
            die("%s:%d: malformed line: %r" % (source, lineno, raw))
        nr_s, _abi, name = fields[0], fields[1], fields[2]
        if not nr_s.isdigit():
            die("%s:%d: bad syscall number %r" % (source, lineno, nr_s))
        nr = int(nr_s)
        if nr >= NR_LIMIT:
            die("%s:%d: syscall number %d outside sanity window" % (source, lineno, nr))
        if not NAME_RE.match(name):
            die("%s:%d: bad syscall name %r" % (source, lineno, name))
        if nr in table:
            die("%s:%d: duplicate syscall number %d" % (source, lineno, nr))
        table[nr] = name
    if not table:
        die("%s: no syscall entries parsed" % source)
    return table


def check_implemented(table, source):
    by_name = {}
    for nr, name in table.items():
        if name in by_name:
            die("%s: syscall name %s appears at multiple nrs" % (source, name))
        by_name[name] = nr
    for name, want_nr in IMPLEMENTED.items():
        if name not in by_name:
            die("%s: implemented syscall %s missing from table" % (source, name))
        if by_name[name] != want_nr:
            die(
                "%s: %s moved: table says nr %d, IMPLEMENTED says %d"
                % (source, name, by_name[name], want_nr)
            )


def emit_header(table, source):
    nr_max = max(table) + 1
    nr_first = min(table)
    nr_last = max(table)
    out = []
    out.append("/*")
    out.append(" * src/os/syscalls_i386.h — generated i386 (int 0x80) syscall table")
    out.append(" *")
    out.append(" * GENERATED by tools/gen_syscall_tab.py — DO NOT EDIT.")
    out.append(" * Source of truth: Linux arch/x86/entry/syscalls/syscall_32.tbl")
    out.append(" *   %s" % source)
    out.append(" * %d syscalls, nr %d..%d (sparse); I686_NR_MAX = %d."
               % (len(table), nr_first, nr_last, nr_max))
    out.append(" *")
    out.append(" * Copyright 2026 Moritz Angermann <moritz@zw3rk.com>, zw3rk pte. ltd.")
    out.append(" * SPDX-License-Identifier: Apache-2.0")
    out.append(" */")
    out.append("")
    out.append("#ifndef %s" % GUARD)
    out.append("#define %s" % GUARD)
    out.append("")
    out.append("#define I686_NR_MAX %d" % nr_max)
    out.append("")
    out.append("typedef struct { const char *name; } i686_sysent_t;")
    out.append("")
    out.append("/* Unassigned slots stay NULL (designated initializers). */")
    out.append("static const i686_sysent_t i686_sysent[I686_NR_MAX] = {")
    for nr in sorted(table):
        out.append("    [%d] = {\"%s\"}," % (nr, table[nr]))
    out.append("};")
    out.append("")
    out.append("/* Numbers for the syscall set implemented by src/os/syscalls.c.")
    out.append(" * The generator cross-checks these against the table above. */")
    macro_width = max(len("I686__NR_" + name) for name in IMPLEMENTED)
    for name in sorted(IMPLEMENTED, key=lambda n: IMPLEMENTED[n]):
        out.append(
            "#define %-*s %dU" % (macro_width, "I686__NR_" + name, IMPLEMENTED[name])
        )
    out.append("")
    out.append("#endif /* %s */" % GUARD)
    out.append("")
    return "\n".join(out)


def main(argv):
    if len(argv) > 2:
        die("usage: %s [output-path]" % argv[0])
    out_path = argv[1] if len(argv) == 2 else None

    sources = []
    env_src = os.environ.get("I686RT_SYSCALL_TBL")
    if env_src:
        sources.append((env_src, fetch_local))
    sources.append((MASTER_URL, fetch_url))
    sources.append((V612_URL, fetch_url))

    text = None
    used_source = None
    for source, fetcher in sources:
        try:
            text = fetcher(source)
            used_source = source
            break
        except Exception as exc:  # noqa: BLE001 — report and try the next source
            sys.stderr.write("gen_syscall_tab: %s: %s\n" % (source, exc))
    if text is None:
        die("could not fetch syscall_32.tbl from any source")

    table = parse_tbl(text, used_source)
    check_implemented(table, used_source)
    header = emit_header(table, used_source)

    if out_path is None:
        sys.stdout.write(header)
    else:
        out_dir = os.path.dirname(out_path)
        if out_dir:
            os.makedirs(out_dir, exist_ok=True)
        with open(out_path, "w", encoding="utf-8") as fh:
            fh.write(header)
    sys.stderr.write(
        "gen_syscall_tab: %s: %d syscalls, nr %d..%d, I686_NR_MAX %d\n"
        % (out_path or "<stdout>", len(table), min(table), max(table), max(table) + 1)
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
