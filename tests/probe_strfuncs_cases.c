/* ------------------------------------------------------------------ */
/* raw int 0x80 syscalls                                              */
/* ------------------------------------------------------------------ */

long sys_write(int fd, const void *buf, unsigned long len)
{
    long r;
    __asm__ volatile ("int $0x80"
                      : "=a"(r)
                      : "a"(4L), "b"((long)fd), "c"(buf), "d"((long)len)
                      : "memory");
    return r;
}

__attribute__((noreturn))
void sys_exit(long code)
{
    __asm__ volatile ("int $0x80" : : "a"(1L), "b"(code));
    __builtin_unreachable();
}

/* ------------------------------------------------------------------ */
/* print helpers                                                      */
/* ------------------------------------------------------------------ */

void put(const char *s, unsigned n)
{
    sys_write(1, s, (unsigned long)n);
}

void puts_(const char *s)
{
    unsigned n = 0u;
    while (s[n] != '\0') {
        n++;
    }
    put(s, n);
}

void put_dec(unsigned v)
{
    char b[10];
    int i = 10;
    if (v == 0u) {
        put("0", 1);
        return;
    }
    while (v != 0u) {
        b[--i] = (char)('0' + (v % 10u));
        v /= 10u;
    }
    put(b + i, (unsigned)(10 - i));
}

void phex(uint32_t v)
{
    static const char hx[16] = "0123456789abcdef";
    char b[8];
    int i;
    for (i = 7; i >= 0; i--) {
        b[i] = hx[v & 0xfu];
        v >>= 4;
    }
    put(b, 8);
}

void phex8(uint8_t v)
{
    static const char hx[16] = "0123456789abcdef";
    char b[2];
    b[0] = hx[v >> 4];
    b[1] = hx[v & 0xfu];
    put(b, 2);
}

/* ------------------------------------------------------------------ */
/* result accounting: append "ok|FAIL" to the open line and count      */
/* ------------------------------------------------------------------ */

unsigned total;
unsigned fails;

void finish(int ok)
{
    puts_(ok ? "ok\n" : "FAIL\n");
    total++;
    if (!ok) {
        fails++;
    }
}

