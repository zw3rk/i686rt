#!/bin/sh
# tools/run-libctest.sh — H2 hardening runner: musl libc-test (static i386)
# binaries built with the docker linux/386 alpine gcc oracle (the
# tools/build_fixture.sh E06-proven pattern) and executed under the
# i686rt translator in an arm64 alpine container.
#
# Per test: bounded timeout (default 30 s), exit status is the libc-test
# convention (0 = pass, non-zero = fail).  Results are appended in a
# TAP-ish log to tests/hardening/results/libctest.tap with per-suite
# "# SUITE <name> pass=.. fail=.. timeout=.. skip=.. total=.." summary
# lines and a final "# RESULT libctest ..." line.
#
# The libc-test tree and its build products are cached under _build/
# (gitignored); H2_FORCE_BUILD=1 forces a rebuild, H2_FORCE_FETCH=1 a
# re-clone.  H2_X87_80=1 runs i686rt with --x87-80 (the exact 80-bit x87
# mode, SPEC decision D9) and writes the TAP log to
# tests/hardening/results/libctest-x87_80.tap instead of libctest.tap
# (the default-mode log is never overwritten); with the knob unset the
# behavior is exactly the default run.  All containers are named,
# resource-limited and timeout-bounded and verified removed (repo test
# lifecycle rules).
#
# Copyright 2026 Moritz Angermann <moritz@zw3rk.com>, zw3rk pte. ltd.
# SPDX-License-Identifier: Apache-2.0

set -eu

# --- configuration (env-overridable) --------------------------------------
ENGINE=${I686RT_ENGINE:-interp}          # engine handed to i686rt
TEST_TIMEOUT=${H2_TEST_TIMEOUT:-30}      # per-test bound (s)
GLOBAL_TIMEOUT=${H2_GLOBAL_TIMEOUT:-5400} # run-loop wall bound (s)
FETCH_TIMEOUT=${H2_FETCH_TIMEOUT:-300}   # git clone bound (s)
BUILD_TIMEOUT=${H2_BUILD_TIMEOUT:-5400}  # make bound (s)
IMAGE=${H2_IMAGE:-alpine:3.20}
FORCE_FETCH=${H2_FORCE_FETCH:-0}
FORCE_BUILD=${H2_FORCE_BUILD:-0}
X87_80=${H2_X87_80:-0}                   # 1 = pass --x87-80 to i686rt (D9)
[ "$X87_80" = 1 ] || X87_80=0            # normalize: unset/other -> default

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
BUILD=$ROOT/_build
CT=$BUILD/libc-test
RESULTS=$ROOT/tests/hardening/results
if [ "$X87_80" = 1 ]; then
    TAP=$RESULTS/libctest-x87_80.tap     # never overwrite the default log
else
    TAP=$RESULTS/libctest.tap
fi
TAP_NAME=${TAP##*/}
INNER_BUILD=$BUILD/.h2-libctest-build.sh
INNER_RUN=$BUILD/.h2-libctest-run.sh

log() { echo "run-libctest.sh: $*"; }
die() { echo "run-libctest.sh: $*" >&2; exit 1; }

sha256_of() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | cut -d' ' -f1
    else
        shasum -a 256 "$1" | cut -d' ' -f1
    fi
}

# Container lifecycle helpers: a leftover container owned by this task is
# stopped/removed before reuse; after every run the removal is verified
# (docker --rm alone does not prove the container exited).
container_clean() {
    docker rm -f "$1" >/dev/null 2>&1 || true
}
container_verify_gone() {
    if docker ps -a --format '{{.Names}}' | LC_ALL=C grep -qx "$1"; then
        die "container $1 still exists after the run (lifecycle violation)"
    fi
}

command -v docker >/dev/null 2>&1 || die "docker not found"
docker ps >/dev/null 2>&1 || die "docker daemon not reachable"
[ -x "$BUILD/i686rt" ] || die "_build/i686rt missing — build it first (see Makefile 'build')"
mkdir -p "$BUILD" "$RESULTS"

# --- 1. fetch (cached under _build/) ---------------------------------------
if [ ! -d "$CT/.git" ] || [ "$FORCE_FETCH" = 1 ]; then
    rm -rf "$CT"
    fetched=0
    for url in \
        https://git.musl-libc.org/libc-test \
        https://repo.or.cz/libc-test.git \
        https://github.com/AssemblyScript/libc-test
    do
        log "fetch: trying $url"
        container_clean h2-libctest-fetch
        if docker run --rm --name h2-libctest-fetch --platform linux/arm64 \
               --memory 2g --cpus 2 -v "$BUILD:/b" \
               -e H2_FETCH_TIMEOUT="$FETCH_TIMEOUT" -e URL="$url" \
               "$IMAGE" sh -c 'timeout "$H2_FETCH_TIMEOUT" sh -c \
                 "apk add -q git ca-certificates && git clone --depth 1 $URL /b/libc-test"'
        then
            fetched=1
            container_verify_gone h2-libctest-fetch
            break
        fi
        container_verify_gone h2-libctest-fetch
        rm -rf "$CT"
    done
    [ "$fetched" = 1 ] || die "all libc-test fetch attempts failed"
fi
CT_URL=$(git -C "$CT" config remote.origin.url 2>/dev/null || echo unknown)
CT_COMMIT=$(git -C "$CT" rev-parse HEAD 2>/dev/null || echo unknown)
log "source: $CT_URL @ $CT_COMMIT"

# --- 2. build static i386 test binaries (linux/386 oracle container) -------
if [ ! -f "$CT/.h2-built" ] || [ "$FORCE_BUILD" = 1 ]; then
    cat > "$INNER_BUILD" <<'EOF'
# generated by tools/run-libctest.sh — do not edit
set -eu
timeout "$H2_BUILD_TIMEOUT" sh -c '
    apk add -q gcc musl-dev make &&
    cd /b/libc-test &&
    { [ -f config.mak ] || cp config.mak.def config.mak; } &&
    find src/functional src/regression src/math -maxdepth 1 -name "*.c" \
        | LC_ALL=C sed "s#^src/\(.*\)\.c\$#src/\1-static.exe#" > /tmp/targets &&
    echo "run-libctest(build): $(wc -l < /tmp/targets) -static.exe targets + src/api/main.exe" &&
    { make -k -j"$(nproc)" $(cat /tmp/targets) src/api/main.exe || \
      echo "run-libctest(build): make -k had target failures (recorded as build-fail skips)"; }
'
echo "run-libctest(build): done"
EOF
    container_clean h2-libctest-build
    rc=0
    docker run --rm --name h2-libctest-build --platform linux/386 \
            --memory 2g --cpus 2 -v "$BUILD:/b" \
            -e H2_BUILD_TIMEOUT="$BUILD_TIMEOUT" \
            "$IMAGE" sh /b/.h2-libctest-build.sh || rc=$?
    container_verify_gone h2-libctest-build
    n=$(find "$CT/src" -name '*-static.exe' 2>/dev/null | wc -l | tr -d ' ')
    [ "$n" -gt 0 ] || die "no static test binaries were built (build log above)"
    {
        echo "# libc-test build stamp (tools/run-libctest.sh)"
        echo "# docker make rc: $rc (non-zero = some targets failed; recorded as build-fail skips)"
        echo "# -static.exe binaries: $n"
        echo "# date: $(date -u '+%FT%TZ')"
    } > "$CT/.h2-built"
    log "built $n static i386 test binaries"
fi

# --- 3. run under i686rt (arm64 container, one process per test) -----------
cat > "$INNER_RUN" <<'EOF'
# generated by tools/run-libctest.sh — do not edit
# Executes every built src/<suite>/<name>-static.exe under /w/i686rt and
# appends TAP-ish rows plus "# SUITE"/"# RESULT" summary lines to $TAP.
set -u
RT=/w/i686rt
TAP=${TAP:?}
: "${TEST_TIMEOUT:=30}"
: "${GLOBAL_TIMEOUT:=5400}"
: "${ENGINE:=interp}"
: "${X87_80:=0}"
rt_flags=""
if [ "$X87_80" = 1 ]; then rt_flags="--x87-80"; fi
export I686RT_ENGINE="$ENGINE"

class_of() {
    _rc=$1
    if grep -q 'not a 32-bit little-endian x86' /tmp/h2.err 2>/dev/null; then
        echo exec-format
    elif [ "$_rc" -ge 129 ] && [ "$_rc" -le 159 ]; then
        # 128+signum (signals 1..31): the translator process died from a
        # host signal; larger exit codes are ordinary exits
        echo "sig$((_rc - 128))"
    elif grep -qi 'function not implemented' /tmp/h2.out 2>/dev/null; then
        echo enosys
    else
        echo "rc$_rc"
    fi
}

i=0
start=$(date +%s)
sum_p=0; sum_f=0; sum_t=0; sum_s=0; sum_tot=0
for suite in functional regression math; do
    p=0; f=0; tmo=0; sk=0; tot=0
    # shellcheck disable=SC2044
    for c_src in $(find "/w/libc-test/src/$suite" -maxdepth 1 -name '*.c' | LC_ALL=C sort); do
        name=${c_src##*/}; name=${name%.c}
        bin="/w/libc-test/src/$suite/$name-static.exe"
        tot=$((tot + 1))
        now=$(date +%s)
        if [ $((now - start)) -gt "$GLOBAL_TIMEOUT" ]; then
            sk=$((sk + 1)); i=$((i + 1))
            printf 'ok %d - %s/%s # SKIP class=global-bound\n' "$i" "$suite" "$name" >> "$TAP"
            continue
        fi
        if [ ! -x "$bin" ]; then
            sk=$((sk + 1)); i=$((i + 1))
            printf 'ok %d - %s/%s # SKIP class=build-fail\n' "$i" "$suite" "$name" >> "$TAP"
            for errf in \
                "/w/libc-test/src/$suite/$name.o.ld.err" \
                "/w/libc-test/src/$suite/$name.o.err"
            do
                if [ -f "$errf" ]; then
                    head -n 1 "$errf" | cut -c1-110 | sed 's/^/# build: /' >> "$TAP"
                    break
                fi
            done
            continue
        fi
        cd /tmp
        timeout -s KILL "$TEST_TIMEOUT" "$RT" $rt_flags -- "$bin" >/tmp/h2.out 2>/tmp/h2.err
        rc=$?
        i=$((i + 1))
        if [ "$rc" -eq 0 ]; then
            p=$((p + 1))
            printf 'ok %d - %s/%s\n' "$i" "$suite" "$name" >> "$TAP"
        elif [ "$rc" -eq 124 ] || [ "$rc" -eq 137 ]; then
            tmo=$((tmo + 1))
            printf 'not ok %d - %s/%s\n# class=timeout\n' "$i" "$suite" "$name" >> "$TAP"
        else
            f=$((f + 1))
            printf 'not ok %d - %s/%s\n# class=%s rc=%d\n' "$i" "$suite" "$name" \
                "$(class_of "$rc")" "$rc" >> "$TAP"
            head -n 1 /tmp/h2.out | cut -c1-110 | sed 's/^/# out: /' >> "$TAP"
        fi
    done
    printf '# SUITE %s pass=%d fail=%d timeout=%d skip=%d total=%d\n' \
        "$suite" "$p" "$f" "$tmo" "$sk" "$tot" >> "$TAP"
    sum_p=$((sum_p + p)); sum_f=$((sum_f + f)); sum_t=$((sum_t + tmo))
    sum_s=$((sum_s + sk)); sum_tot=$((sum_tot + tot))
done
printf '# RESULT libctest pass=%d fail=%d timeout=%d skip=%d total=%d\n' \
    "$sum_p" "$sum_f" "$sum_t" "$sum_s" "$sum_tot" >> "$TAP"
# api suite provenance: its checks are compile-time (the oracle's musl headers
# are what gets checked); the runtime binary is dynamic-only.  Recorded for
# the report, outside the runtime totals (see tests/hardening/README.md).
api_cs=$(find /w/libc-test/src/api -name '*.c' | wc -l)
api_os=$(find /w/libc-test/src/api -name '*.o' | wc -l)
printf '# API api-compile compiled=%s of=%s main.exe=dynamic-only\n' \
    "$api_os" "$api_cs" >> "$TAP"
printf '# WALL seconds=%d\n' "$(( $(date +%s) - start ))" >> "$TAP"
printf '1..%d\n' "$i" >> "$TAP"
EOF
container_clean h2-libctest-run
: > "$TAP"
{
    echo "# H2 libctest run — generated by tools/run-libctest.sh (do not edit)"
    echo "# date: $(date -u '+%FT%TZ')"
    echo "# host: $(uname -sm)"
    echo "# i686rt: sha256=$(sha256_of "$BUILD/i686rt")"
    echo "# engine: $ENGINE   per-test-timeout: ${TEST_TIMEOUT}s   global-bound: ${GLOBAL_TIMEOUT}s"
    if [ "$X87_80" = 1 ]; then
        echo "# x87: 80-bit exact mode (--x87-80; SPEC D9 measurement, H2_X87_80=1)"
    fi
    echo "# containers: runtime $IMAGE linux/arm64, build $IMAGE linux/386 (gcc oracle)"
    echo "# source: $CT_URL @ $CT_COMMIT"
    echo "# suites: functional, regression, math (static -static.exe binaries;"
    echo "#         api is compile-time-only and documented in tests/hardening/README.md)"
} > "$TAP"
rc=0
docker run --rm --name h2-libctest-run --platform linux/arm64 \
        --memory 2g --cpus 2 \
        -v "$BUILD:/w" -v "$RESULTS:/res" \
        -e TAP="/res/$TAP_NAME" \
        -e TEST_TIMEOUT="$TEST_TIMEOUT" -e GLOBAL_TIMEOUT="$GLOBAL_TIMEOUT" \
        -e X87_80="$X87_80" \
        "$IMAGE" sh /w/.h2-libctest-run.sh || rc=$?
container_verify_gone h2-libctest-run
[ "$rc" -eq 0 ] || die "run container exited rc=$rc"

# --- 4. verify the log ------------------------------------------------------
grep -q '^# RESULT libctest ' "$TAP" || die "no RESULT line in $TAP"
total=$(sed -n 's/^# RESULT libctest .* total=\([0-9]*\)$/\1/p' "$TAP")
[ "${total:-0}" -gt 0 ] || die "zero tests recorded in $TAP"
grep '^# RESULT ' "$TAP"
log "ok: results in $TAP"
