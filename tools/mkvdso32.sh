#!/bin/sh
# tools/mkvdso32.sh — build + verify the synthetic i386 vDSO, emit the C blob
#
# Copyright 2026 Moritz Angermann <moritz@zw3rk.com>, zw3rk pte. ltd.
# SPDX-License-Identifier: Apache-2.0
#
# Assembles src/os/vdso32/vdso32.S and links it with vdso32.lds inside
# docker (linux/386 alpine via qemu-user on Apple Silicon), matching the
# kernel's own vdso32 link (arch/x86/entry/vdso/vdso32/Makefile:
# -m elf_i386 -soname linux-gate.so.1).  Verifies the image with
# readelf — ELF32/EM_386/ET_DYN, e_entry == __kernel_vsyscall, all 8
# exported symbols GLOBAL DEFAULT, LINUX_2.5 + LINUX_2.6 verdefs — and
# regenerates src/os/vdso32_blob.c from the .so bytes.
#
# The .o/.so products stay in src/os/vdso32/ (gitignored); the committed
# artifact is the generated blob .c.  Needs: docker, od(1), awk(1).

set -eu

root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
srcdir="$root/src/os/vdso32"
so="$srcdir/vdso32.so"
blob_c="$root/src/os/vdso32_blob.c"

IMG=alpine:3.20

echo "== assembling + linking vdso32 (docker $IMG, linux/386)"
docker run --rm -v "$root":/w --platform linux/386 "$IMG" sh -c '
    set -e
    apk add -q --no-cache binutils >/dev/null
    cd /w/src/os/vdso32
    as --32 -o vdso32.o vdso32.S
    ld -m elf_i386 -shared -T vdso32.lds \
       --hash-style=sysv --build-id=none -soname linux-gate.so.1 \
       -o vdso32.so vdso32.o
'

echo "== readelf verification"
readelf_out=$(docker run --rm -v "$srcdir":/v --platform linux/386 "$IMG" sh -c '
    set -e
    apk add -q --no-cache binutils >/dev/null
    readelf -h /v/vdso32.so
    echo "=== DYNSYMS"
    readelf -W --dyn-syms /v/vdso32.so
    echo "=== VERSIONINFO"
    readelf -W -V /v/vdso32.so
')

hdr=$(printf '%s\n' "$readelf_out" | sed -n '/=== DYNSYMS/q;p')
dynsyms=$(printf '%s\n' "$readelf_out" | sed -n '/=== DYNSYMS/,/=== VERSIONINFO/p')
verinfo=$(printf '%s\n' "$readelf_out" | sed -n '/=== VERSIONINFO/,$p')

# Header: ELF32, little-endian, EM_386, ET_DYN, and e_entry.
for pat in 'Class:.*ELF32' 'Data:.*little' 'Machine:.*Intel 80386' 'Type:.*DYN'; do
    printf '%s\n' "$hdr" | grep -q "$pat" || { echo "FAIL: missing '$pat'" >&2; exit 1; }
done
entry=$(printf '%s\n' "$hdr" | sed -n 's/.*Entry point address:[[:space:]]*//p' | tr -d ' ')

# Dynamic symbols: all eight present, GLOBAL DEFAULT, exactly once.
# (Names print as sym@@VER; anchor with an explicit @@/end boundary so
# __vdso_clock_gettime does not match __vdso_clock_gettime64.)
for sym in __kernel_vsyscall __kernel_sigreturn __kernel_rt_sigreturn \
           __vdso_clock_gettime __vdso_clock_gettime64 __vdso_gettimeofday \
           __vdso_time __vdso_clock_getres; do
    n=$(printf '%s\n' "$dynsyms" | awk -v s="$sym" \
        '$5 == "GLOBAL" && $6 == "DEFAULT" && $8 ~ "^" s "(@@|$)" { c++ } END { print c + 0 }')
    if [ "$n" -ne 1 ]; then
        echo "FAIL: symbol $sym found $n times as GLOBAL DEFAULT (want 1)" >&2
        exit 1
    fi
done
gcount=$(printf '%s\n' "$dynsyms" | awk '$4 == "FUNC" && $5 == "GLOBAL" && $6 == "DEFAULT" { c++ } END { print c + 0 }')
if [ "$gcount" -ne 8 ]; then
    echo "FAIL: $gcount FUNC GLOBAL DEFAULT dynsyms exported (want exactly 8)" >&2
    exit 1
fi

# e_entry must equal the __kernel_vsyscall dynsym value (E07: AT_SYSINFO
# == vdso_base + e_entry == &__kernel_vsyscall).
vsym=$(printf '%s\n' "$dynsyms" | awk '$8 ~ /^__kernel_vsyscall(@@|$)/ { print $2 }')
norm_entry=$(printf '%s\n' "$entry" | sed 's/^0x//; s/^0*//')
norm_vsym=$(printf '%s\n' "$vsym" | sed 's/^0x//; s/^0*//')
if [ -z "$norm_entry" ] || [ "$norm_entry" != "$norm_vsym" ]; then
    echo "FAIL: e_entry ($entry) != __kernel_vsyscall ($vsym)" >&2
    exit 1
fi

# Version definitions: both LINUX_2.5 and LINUX_2.6.
for ver in LINUX_2.5 LINUX_2.6; do
    printf '%s\n' "$verinfo" | grep -q "Name: $ver" || {
        echo "FAIL: verdef $ver missing" >&2; exit 1; }
done
vercount=$(printf '%s\n' "$verinfo" | grep -c 'LINUX_2')
if [ "$vercount" -lt 2 ]; then
    echo "FAIL: expected at least 2 LINUX_2* version lines, got $vercount" >&2
    exit 1
fi

echo "   e_entry == __kernel_vsyscall @ 0x$norm_vsym"
printf '%s\n' "$dynsyms" | awk '$4 == "FUNC" && $5 == "GLOBAL" && $6 == "DEFAULT" { printf "   %s %s\n", $2, $8 }'

echo "== generating $blob_c"
size=$(wc -c < "$so" | tr -d ' ')
if command -v sha256sum >/dev/null 2>&1; then
    sha=$(sha256sum "$so" | awk '{ print $1 }')
else
    sha=$(shasum -a 256 "$so" | awk '{ print $1 }')
fi

{
    cat <<EOF
/*
 * src/os/vdso32_blob.c — embedded synthetic i386 vDSO image (SPEC D12, E07)
 *
 * GENERATED by tools/mkvdso32.sh — DO NOT EDIT.
 * Built from src/os/vdso32/vdso32.S + vdso32.lds (docker linux/386
 * alpine:3.20: as --32, ld -m elf_i386 -shared -T vdso32.lds).
 * vdso32.so: $size bytes, sha256 $sha
 *
 * Copyright 2026 Moritz Angermann <moritz@zw3rk.com>, zw3rk pte. ltd.
 * SPDX-License-Identifier: Apache-2.0
 */

const unsigned char i686_vdso32_blob[] = {
EOF
    od -An -v -tx1 "$so" | awk '
        {
            for (i = 1; i <= NF; i++) {
                if (n % 16 == 0) printf "    "
                printf "0x%s,", $i
                n++
                if (n % 16 == 0) printf "\n"
            }
        }
        END { if (n % 16 != 0) printf "\n" }'
    cat <<EOF
};

const unsigned long i686_vdso32_blob_size = sizeof i686_vdso32_blob;
EOF
} > "$blob_c"

echo "== done: $size-byte vDSO, blob written"
