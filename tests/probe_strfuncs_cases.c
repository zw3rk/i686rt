uint32_t ld32(const uint8_t *s)
{
    return (uint32_t)s[0] | ((uint32_t)s[1] << 8) |
           ((uint32_t)s[2] << 16) | ((uint32_t)s[3] << 24);
}

uint64_t ld64(const uint8_t *s)
{
    return (uint64_t)ld32(s) | ((uint64_t)ld32(s + 4) << 32);
}

int v8_eq(const uint8_t *a, const uint8_t *b)
{
    unsigned i;
    for (i = 0u; i < 8u; i++) {
        if (a[i] != b[i]) {
            return 0;
        }
    }
    return 1;
}

char *ref_strchr(const char *s, int c)
{
    char t = (char)c;
    for (; *s != '\0'; s++) {
        if (*s == t) {
            return (char *)s;
        }
    }
    return t == '\0' ? (char *)s : (char *)0;
}

char *ref_strrchr(const char *s, int c)
{
    char t = (char)c;
    char *last = (char *)0;
    for (; ; s++) {
        if (*s == t) {
            last = (char *)s;
        }
        if (*s == '\0') {
            break;
        }
    }
    return last;
}

const void *ref_memchr(const char *s, int c, unsigned long n)
{
    char t = (char)c;
    unsigned long i;
    for (i = 0u; i < n; i++) {
        if (s[i] == t) {
            return s + i;
        }
    }
    return 0;
}

unsigned long ref_strlen(const char *s)
{
    unsigned long n = 0u;
    while (s[n] != '\0') {
        n++;
    }
    return n;
}

