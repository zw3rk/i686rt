static _Alignas(64) uint8_t buf[512];

void fill_pattern(uint8_t *p, unsigned n, uint8_t seed)
{
    unsigned i;
    uint8_t x = seed;
    for (i = 0u; i < n; i++) {
        x = (uint8_t)(x * 31u + 7u);
        if (x == 0u || x == (uint8_t)'/') {
            x = (uint8_t)(x + 17u);
        }
        p[i] = x;
    }
}

void blob_case(const char *fn, const char *cs, unsigned off,
                      const char *s, int c)
{
    char *g, *e;
    unsigned long got, exp;

    if (fn[1] == 'h') {
        g = t2_strchr_sse2(s, c);
        e = ref_strchr(s, c);
    } else {
        g = t2_strrchr_sse2(s, c);
        e = ref_strrchr(s, c);
    }
    got = (g == 0) ? 0xFFFFFFFFul : (unsigned long)(g - (char *)buf);
    exp = (e == 0) ? 0xFFFFFFFFul : (unsigned long)(e - (char *)buf);
    puts_("SF ");
    puts_(fn);
    put(" ", 1);
    puts_(cs);
    put(" o=", 3);
    phex((uint32_t)off);
    put(" c=", 3);
    phex((uint32_t)(uint8_t)c);
    put(" got=", 5);
    phex((uint32_t)got);
    put(" exp=", 5);
    phex((uint32_t)exp);
    put(" ", 1);
    finish(g == e);
}

