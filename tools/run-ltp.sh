#!/bin/sh
# tools/run-ltp.sh — H2 hardening runner: bounded Linux Test Project subset
# (release 20240930) built as static i386 binaries with the docker
# linux/386 alpine gcc oracle (the tools/build_fixture.sh E06-proven
# pattern) and executed under the i686rt translator in an arm64 alpine
# container.
#
# Subset (justified in tests/hardening/README.md): only the syscall test
# directories write, read, fork, mmap, fcntl, socket are built — they map
# onto implemented syscall families (file I/O, process creation, memory
# management, record locks, and the i386 socketcall multiplexer).  No
# full-LTP clone/build.
#
# Exit status convention (LTP): rc 0 = pass; rc bit 32 (TCONF) without
# bits 1/2 (TFAIL/TBROK) = skip; 124/137 = timed out.  Results are
# appended in a TAP-ish log to tests/hardening/results/ltp.tap with
# per-directory "# SUITE <dir> pass=.. fail=.. timeout=.. skip=.. total=.."
# lines and a final "# RESULT ltp ..." line.
#
# The tree and build products are cached under _build/ (gitignored);
# H2_FORCE_BUILD=1 forces a rebuild, H2_FORCE_FETCH=1 a re-download.
# All containers are named, resource-limited and timeout-bounded and
# verified removed (repo test lifecycle rules).
#
# Copyright 2026 Moritz Angermann <moritz@zw3rk.com>, zw3rk pte. ltd.
# SPDX-License-Identifier: Apache-2.0

set -eu

# --- configuration (env-overridable) --------------------------------------
ENGINE=${I686RT_ENGINE:-interp}           # engine handed to i686rt
TEST_TIMEOUT=${H2_TEST_TIMEOUT:-30}       # per-test bound (s)
GLOBAL_TIMEOUT=${H2_GLOBAL_TIMEOUT:-3600} # run-loop wall bound (s)
FETCH_TIMEOUT=${H2_FETCH_TIMEOUT:-900}    # tarball download/clone bound (s)
BUILD_TIMEOUT=${H2_BUILD_TIMEOUT:-5400}   # configure+make bound (s)
IMAGE=${H2_IMAGE:-alpine:3.20}
LTP_TAG=${H2_LTP_TAG:-20240930}
FORCE_FETCH=${H2_FORCE_FETCH:-0}
FORCE_BUILD=${H2_FORCE_BUILD:-0}
LTP_DIRS='write read fork mmap fcntl socket'

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
BUILD=$ROOT/_build
LTP=$BUILD/ltp-$LTP_TAG
RESULTS=$ROOT/tests/hardening/results
TAP=$RESULTS/ltp.tap
INNER_BUILD=$BUILD/.h2-ltp-build.sh
INNER_RUN=$BUILD/.h2-ltp-run.sh

TARBALL_URL="https://github.com/linux-test-project/ltp/releases/download/$LTP_TAG/ltp-full-$LTP_TAG.tar.xz"
SHA_URL="$TARBALL_URL.sha256"
GIT_URL="https://github.com/linux-test-project/ltp"

log() { echo "run-ltp.sh: $*"; }
die() { echo "run-ltp.sh: $*" >&2; exit 1; }

sha256_of() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | cut -d' ' -f1
    else
        shasum -a 256 "$1" | cut -d' ' -f1
    fi
}

container_clean() {
    docker rm -f "$1" >/dev/null 2>&1 || true
}
container_verify_gone() {
    if docker ps -a --format '{{.Names}}' | LC_ALL=C grep -qx "$1"; then
        die "container $1 still exists after the run (lifecycle violation)"
    fi
}

command -v docker >/dev/null 2>&1 || die "docker not found"
docker ps >/dev/null 2>&1 || die "docker daemon not reachable"
[ -x "$BUILD/i686rt" ] || die "_build/i686rt missing — build it first (see Makefile 'build')"
mkdir -p "$BUILD" "$RESULTS"

# --- 1. fetch the bounded release tree (cached under _build/) --------------
if [ ! -f "$LTP/.h2-fetched" ] || [ "$FORCE_FETCH" = 1 ]; then
    rm -rf "$LTP"
    fetched=0
    cat > "$BUILD/.h2-ltp-fetch.sh" <<'EOF'
# generated by tools/run-ltp.sh — do not edit
set -eu
timeout "$H2_FETCH_TIMEOUT" sh -c '
    apk add -q curl xz tar &&
    cd /b &&
    curl -fsSL --retry 2 -o ltp.tar.xz "$TARBALL_URL" &&
    curl -fsSL --retry 2 -o ltp.sha256 "$SHA_URL" &&
    echo "$(LC_ALL=C cut -d" " -f1 ltp.sha256)  ltp.tar.xz" | sha256sum -c - &&
    tar -tJf ltp.tar.xz >/dev/null &&
    topdir=$(tar -tJf ltp.tar.xz | LC_ALL=C head -n 1 | LC_ALL=C cut -d/ -f1) &&
    tar -xJf ltp.tar.xz -C /b &&
    mv "/b/$topdir" /b/ltp-dst &&
    echo "run-ltp(fetch): extracted $topdir (sha256 $(sha256sum ltp.tar.xz | cut -d" " -f1))"
'
EOF
    container_clean h2-ltp-fetch
    log "fetch: trying release tarball $TARBALL_URL"
    if docker run --rm --name h2-ltp-fetch --platform linux/arm64 \
            --memory 2g --cpus 2 -v "$BUILD:/b" \
            -e H2_FETCH_TIMEOUT="$FETCH_TIMEOUT" \
            -e TARBALL_URL="$TARBALL_URL" -e SHA_URL="$SHA_URL" \
            "$IMAGE" sh /b/.h2-ltp-fetch.sh
    then
        mv "$BUILD/ltp-dst" "$LTP"
        fetched=1
    fi
    container_verify_gone h2-ltp-fetch
    if [ "$fetched" = 0 ]; then
        log "fetch: tarball failed; trying shallow git clone at tag $LTP_TAG"
        container_clean h2-ltp-fetch
        if docker run --rm --name h2-ltp-fetch --platform linux/arm64 \
                --memory 2g --cpus 2 -v "$BUILD:/b" \
                -e H2_FETCH_TIMEOUT="$FETCH_TIMEOUT" -e GIT_URL="$GIT_URL" -e LTP_TAG="$LTP_TAG" \
                "$IMAGE" sh -c 'timeout "$H2_FETCH_TIMEOUT" sh -c \
                  "apk add -q git ca-certificates && git clone --depth 1 --branch $LTP_TAG $GIT_URL /b/ltp-dst"'
        then
            mv "$BUILD/ltp-dst" "$LTP"
            fetched=1
        fi
        container_verify_gone h2-ltp-fetch
    fi
    [ "$fetched" = 1 ] || die "all LTP fetch attempts failed"
    {
        echo "# LTP fetch stamp (tools/run-ltp.sh)"
        echo "# source: $TARBALL_URL (fallback: $GIT_URL branch $LTP_TAG)"
        echo "# tarball sha256: $( [ -f "$BUILD/ltp.tar.xz" ] && sha256_of "$BUILD/ltp.tar.xz" || echo n/a-git-clone)"
        echo "# date: $(date -u '+%FT%TZ')"
    } > "$LTP/.h2-fetched"
fi

# --- 2. build the static i386 subset (linux/386 oracle container) ----------
if [ ! -f "$LTP/.h2-built" ] || [ "$FORCE_BUILD" = 1 ]; then
    cat > "$INNER_BUILD" <<'EOF'
# generated by tools/run-ltp.sh — do not edit
#
# NOTE 1: static linking comes from configure (LDFLAGS=-static is baked
# into include/mk/config.mk); it must NOT be re-passed on the make command
# line — a command-line LDFLAGS would replace the -L$(top_builddir)/lib
# that include/mk/env_post.mk appends, and every -lltp link would fail.
# NOTE 2: FILTER_OUT_DIRS rides MAKEFLAGS into the recursive
# "make -C lib all" (include/mk/testcases.mk) and keeps lib/newlib_tests
# and lib/tests — LTP internal framework unit tests that cannot
# bootstrap-link against -lltp — out of the build; only libltp.a matters
# for the syscall dirs.
set -eu
: "${LTP_TREE:?}"
timeout "$H2_BUILD_TIMEOUT" sh -c '
    apk add -q gcc musl-dev make autoconf automake pkgconfig flex bison \
        perl linux-headers file &&
    cd "/b/$LTP_TREE" &&
    make autotools &&
    LDFLAGS=-static ./configure > /tmp/ltp-configure.log 2>&1 || {
        echo "run-ltp(build): configure FAILED; tail of log:"; tail -n 30 /tmp/ltp-configure.log; exit 1; }
    make -j"$(nproc)" -C lib libltp.a > /tmp/ltp-lib.log 2>&1 || {
        echo "run-ltp(build): libltp.a FAILED; tail of log:"; tail -n 30 /tmp/ltp-lib.log; exit 1; }
    for d in $LTP_DIRS; do
        make -k -j"$(nproc)" -C "testcases/kernel/syscalls/$d" \
            FILTER_OUT_DIRS="android_libpthread android_librt newlib_tests tests" \
            > "/tmp/ltp-$d.log" 2>&1 \
            || echo "run-ltp(build): $d had build failures (recorded as build-fail skips)"
    done
    : > "/b/$LTP_TREE/.h2-tests.list"
    for d in $LTP_DIRS; do
        for f in "testcases/kernel/syscalls/$d"/*; do
            [ -f "$f" ] || continue
            case "$f" in
                *.c|*.o|*.h|*.d|*.sh|Makefile|*.mk) continue ;;
            esac
            [ -x "$f" ] || continue
            desc=$(file -b "$f")
            case "$desc" in
                # file(1) emits "ELF 32-bit LSB executable, Intel 80386, ..."
                *"ELF 32-bit"*"executable"*"Intel 80386"*)
                    case "$desc" in
                        *"statically linked"*) kind=static ;;
                        *) kind=dynamic ;;
                    esac
                    printf "%s %s %s\n" "$kind" "$d" "$f" >> "/b/$LTP_TREE/.h2-tests.list"
                    ;;
            esac
        done
    done
    echo "run-ltp(build): $(wc -l < "/b/$LTP_TREE/.h2-tests.list") ELF executables recorded"
'
echo "run-ltp(build): done"
EOF
    container_clean h2-ltp-build
    rc=0
    docker run --rm --name h2-ltp-build --platform linux/386 \
            --memory 2g --cpus 2 -v "$BUILD:/b" \
            -e H2_BUILD_TIMEOUT="$BUILD_TIMEOUT" -e LTP_DIRS="$LTP_DIRS" \
            -e LTP_TREE="$(basename "$LTP")" \
            "$IMAGE" sh /b/.h2-ltp-build.sh || rc=$?
    container_verify_gone h2-ltp-build
    [ "$rc" -eq 0 ] || die "LTP build container failed (rc=$rc; configure/lib errors above)"
    n=$(wc -l < "$LTP/.h2-tests.list" | tr -d ' ')
    [ "$n" -gt 0 ] || die "no LTP test executables were built (build log above)"
    {
        echo "# LTP build stamp (tools/run-ltp.sh)"
        echo "# test executables: $n (dirs: $LTP_DIRS; static + dynamic ELF)"
        echo "# date: $(date -u '+%FT%TZ')"
    } > "$LTP/.h2-built"
    log "built $n LTP test executables"
    # free the container-local copy; the built tree stays in $LTP
    rm -f "$BUILD/ltp.tar.xz" "$BUILD/ltp.sha256"
fi

# --- 3. run under i686rt (arm64 container, one process per test) -----------
cat > "$INNER_RUN" <<'EOF'
# generated by tools/run-ltp.sh — do not edit
# Executes every recorded test executable under /w/i686rt and appends
# TAP-ish rows plus "# SUITE"/"# RESULT" summary lines to $TAP.
set -u
RT=/w/i686rt
TAP=${TAP:?}
: "${LTP_TREE:?}"
: "${TEST_TIMEOUT:=30}"
: "${GLOBAL_TIMEOUT:=3600}"
: "${ENGINE:=interp}"
export I686RT_ENGINE="$ENGINE"

class_of() {
    _rc=$1
    if grep -q 'not a 32-bit little-endian x86' /tmp/h2.err 2>/dev/null; then
        echo exec-format
    elif [ "$_rc" -ge 129 ] && [ "$_rc" -le 159 ]; then
        # 128+signum (signals 1..31): the translator process died from a
        # host signal; larger exit codes are ordinary exits
        echo "sig$((_rc - 128))"
    elif grep -qi 'function not implemented' /tmp/h2.out 2>/dev/null; then
        echo enosys
    else
        echo "rc$_rc"
    fi
}

i=0
start=$(date +%s)
sum_p=0; sum_f=0; sum_t=0; sum_s=0; sum_tot=0
for suite in $LTP_DIRS; do
    p=0; f=0; tmo=0; sk=0; tot=0
    LC_ALL=C awk -v s="$suite" '$2 == s' "/w/$LTP_TREE/.h2-tests.list" \
        | LC_ALL=C sort -k3 > /tmp/h2-suite.list
    while read -r kind dir path; do
        [ -n "$kind" ] || continue
        name=${path##*/}
        tot=$((tot + 1))
        now=$(date +%s)
        if [ $((now - start)) -gt "$GLOBAL_TIMEOUT" ]; then
            sk=$((sk + 1)); i=$((i + 1))
            printf 'ok %d - %s/%s # SKIP class=global-bound\n' "$i" "$suite" "$name" >> "$TAP"
            continue
        fi
        if [ "$kind" != static ]; then
            sk=$((sk + 1)); i=$((i + 1))
            printf 'ok %d - %s/%s # SKIP class=design-dynamic\n' "$i" "$suite" "$name" >> "$TAP"
            continue
        fi
        cd /tmp
        # The guest path must be ABSOLUTE: the translator resolves it
        # against its own cwd (/tmp here), so a bare $path would look
        # for /tmp/testcases/... and every test would exit 1 without
        # running (vacuous all-fail logs; found by the fix-campaign C1
        # acceptance rerun).
        timeout -s KILL "$TEST_TIMEOUT" "$RT" -- "/w/$LTP_TREE/$path" >/tmp/h2.out 2>/tmp/h2.err
        rc=$?
        i=$((i + 1))
        if [ "$rc" -eq 0 ]; then
            p=$((p + 1))
            printf 'ok %d - %s/%s\n' "$i" "$suite" "$name" >> "$TAP"
        elif [ "$rc" -eq 124 ] || [ "$rc" -eq 137 ]; then
            tmo=$((tmo + 1))
            printf 'not ok %d - %s/%s\n# class=timeout\n' "$i" "$suite" "$name" >> "$TAP"
        elif [ "$((rc & 32))" -ne 0 ] && [ "$((rc & 3))" -eq 0 ]; then
            # TCONF without TFAIL/TBROK: test.conf skipped (missing feature)
            sk=$((sk + 1))
            printf 'ok %d - %s/%s # SKIP class=tconf\n' "$i" "$suite" "$name" >> "$TAP"
            head -n 1 /tmp/h2.out | cut -c1-110 | sed 's/^/# out: /' >> "$TAP"
        else
            f=$((f + 1))
            printf 'not ok %d - %s/%s\n# class=%s rc=%d\n' "$i" "$suite" "$name" \
                "$(class_of "$rc")" "$rc" >> "$TAP"
            head -n 1 /tmp/h2.out | cut -c1-110 | sed 's/^/# out: /' >> "$TAP"
        fi
    done < /tmp/h2-suite.list
    printf '# SUITE %s pass=%d fail=%d timeout=%d skip=%d total=%d\n' \
        "$suite" "$p" "$f" "$tmo" "$sk" "$tot" >> "$TAP"
    sum_p=$((sum_p + p)); sum_f=$((sum_f + f)); sum_t=$((sum_t + tmo))
    sum_s=$((sum_s + sk)); sum_tot=$((sum_tot + tot))
done
printf '# RESULT ltp pass=%d fail=%d timeout=%d skip=%d total=%d\n' \
    "$sum_p" "$sum_f" "$sum_t" "$sum_s" "$sum_tot" >> "$TAP"
printf '# WALL seconds=%d\n' "$(( $(date +%s) - start ))" >> "$TAP"
printf '1..%d\n' "$i" >> "$TAP"
EOF
container_clean h2-ltp-run
: > "$TAP"
{
    echo "# H2 LTP-subset run — generated by tools/run-ltp.sh (do not edit)"
    echo "# date: $(date -u '+%FT%TZ')"
    echo "# host: $(uname -sm)"
    echo "# i686rt: sha256=$(sha256_of "$BUILD/i686rt")"
    echo "# engine: $ENGINE   per-test-timeout: ${TEST_TIMEOUT}s   global-bound: ${GLOBAL_TIMEOUT}s"
    echo "# containers: runtime $IMAGE linux/arm64, build $IMAGE linux/386 (gcc oracle)"
    echo "# source: $TARBALL_URL (tag $LTP_TAG)"
    echo "# suites: $LTP_DIRS (selection rationale: tests/hardening/README.md)"
} > "$TAP"
rc=0
docker run --rm --name h2-ltp-run --platform linux/arm64 \
        --memory 2g --cpus 2 \
        -v "$BUILD:/w" -v "$RESULTS:/res" \
        -e TAP=/res/ltp.tap \
        -e TEST_TIMEOUT="$TEST_TIMEOUT" -e GLOBAL_TIMEOUT="$GLOBAL_TIMEOUT" \
        -e LTP_DIRS="$LTP_DIRS" -e LTP_TREE="$(basename "$LTP")" \
        "$IMAGE" sh /w/.h2-ltp-run.sh || rc=$?
container_verify_gone h2-ltp-run
[ "$rc" -eq 0 ] || die "run container exited rc=$rc"

# --- 4. verify the log ------------------------------------------------------
grep -q '^# RESULT ltp ' "$TAP" || die "no RESULT line in $TAP"
total=$(sed -n 's/^# RESULT ltp .* total=\([0-9]*\)$/\1/p' "$TAP")
[ "${total:-0}" -gt 0 ] || die "zero tests recorded in $TAP"
grep '^# RESULT ' "$TAP"
log "ok: results in $TAP"
