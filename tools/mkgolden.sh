#!/bin/sh
#
# tools/mkgolden.sh — regenerate the Phase 5 FPU/SSE golden outputs
#
# Usage: tools/mkgolden.sh [--fixture-only]
#
# Builds tests/test_p5_fpu_sse.c with the docker linux/386 alpine gcc
# toolchain (E06-proven QEMU TCG oracle; pattern from
# tools/build_fixture.sh, but with -msse -msse2 -mno-mmx so the binary
# may contain the fixture's deliberately hand-written SSE), runs the
# fixture TWICE on the oracle and requires byte-identical output, then
# writes:
#
#   tests/golden/p5.txt         full oracle run; the default-mode RC5
#                               check compares these lines minus the
#                               ones marked X87ONLY (i686rt's default
#                               mode models 64-bit doubles per ST, D9)
#   tests/golden/p5_x87_80.txt  the same full oracle run; the RC5
#                               --x87-80 check compares every line (the
#                               oracle IS exact 80-bit x87 hardware)
#
# Idempotent: re-running rewrites both files from scratch.  The fixture
# output itself is fully deterministic (fixed constants, no environ).
#
# Copyright 2026 Moritz Angermann <moritz@zw3rk.com>, zw3rk pte. ltd.
# SPDX-License-Identifier: Apache-2.0

set -eu

root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$root"

fixture_only=0
if [ "${1:-}" = "--fixture-only" ]; then
    fixture_only=1
elif [ "$#" -gt 0 ]; then
    echo "usage: tools/mkgolden.sh [--fixture-only]" >&2
    exit 2
fi

mkdir -p _build tests/golden

# Bounded, named, and cleaned up per the test-process lifecycle rules.
cid=_build/mkgolden.cid
cleanup() {
    docker rm -f mkgolden-l5e >/dev/null 2>&1 || true
    rm -f "$cid"
}
trap cleanup EXIT INT TERM

docker run --rm --name mkgolden-l5e --cidfile "$cid" \
    --platform linux/386 \
    --memory 1g --cpus 2 \
    -v "$root":/w \
    alpine:3.20 \
    timeout 180 sh -c "
        apk add --no-cache gcc musl-dev >/dev/null &&
        cd /w &&
        cc -std=c11 -Wall -Wextra -ffreestanding -static -nostdlib -O2 \
           -march=i686 -msse -msse2 -mno-mmx -fno-pie -fno-stack-protector \
           -o _build/test_p5_fpu_sse tests/test_p5_fpu_sse.c &&
        timeout 60 ./_build/test_p5_fpu_sse > _build/p5_run1.txt &&
        timeout 60 ./_build/test_p5_fpu_sse > _build/p5_run2.txt &&
        cmp _build/p5_run1.txt _build/p5_run2.txt &&
        tail -n 1 _build/p5_run1.txt | grep -q '^DONE [0-9][0-9]*$'
    "

desc=$(file -b _build/test_p5_fpu_sse)
case $desc in
    *"ELF 32-bit LSB executable, Intel 80386"*) ;;
    *)
        echo "mkgolden.sh: fixture is not an i386 static ELF: $desc" >&2
        exit 1
        ;;
esac

if [ "$fixture_only" = 1 ]; then
    echo "mkgolden.sh: _build/test_p5_fpu_sse built and oracle-verified"
    exit 0
fi

date=$(date -u +%Y-%m-%d)
prov="# golden: docker --platform linux/386 alpine:3.20 gcc, QEMU TCG x87/SSE oracle (E06); $date"
{
    echo "$prov"
    echo "# golden: fixture tests/test_p5_fpu_sse.c (-march=i686 -msse -msse2 -mno-mmx)"
    echo "# golden: generated by tools/mkgolden.sh - do not edit; regenerate instead"
    echo "# golden: p5.txt = full oracle run; default-mode checks skip CASE X87ONLY lines"
    cat _build/p5_run1.txt
} > tests/golden/p5.txt

{
    echo "$prov"
    echo "# golden: fixture tests/test_p5_fpu_sse.c (-march=i686 -msse -msse2 -mno-mmx)"
    echo "# golden: generated by tools/mkgolden.sh - do not edit; regenerate instead"
    echo "# golden: p5_x87_80.txt = same full oracle run; --x87-80 checks compare every line"
    cat _build/p5_run1.txt
} > tests/golden/p5_x87_80.txt

echo "mkgolden.sh: wrote tests/golden/p5.txt and tests/golden/p5_x87_80.txt \
($(grep -c '^CASE' tests/golden/p5.txt) cases)"
