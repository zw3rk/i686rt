/*
 * src/os/vdso.c — map the embedded synthetic i386 vDSO (SPEC D12, E07)
 *
 * Copyright 2026 Moritz Angermann <moritz@zw3rk.com>, zw3rk pte. ltd.
 * SPDX-License-Identifier: Apache-2.0
 *
 * The image (src/os/vdso32_blob.c, built by tools/mkvdso32.sh from
 * src/os/vdso32/vdso32.S + vdso32.lds) is a static, hand-written ELF32
 * EM_386 ET_DYN object.  Assumptions, all verified at parse time:
 *   - a single PT_LOAD (r-x) starting at vaddr 0 carries the ELF and
 *     program headers, the dynamic tables and .text, so mapping the
 *     PT_LOAD bytes is the whole image — no segment splitting;
 *   - every exported symbol is absolute at link time: the image has no
 *     relocations, so no relocation processing exists or is needed
 *     (.dynamic is parsed read-only, for symbol resolution);
 *   - e_entry == .dynsym __kernel_vsyscall (checked), so AT_SYSINFO
 *     can equivalently be taken as vdso_base + e_entry (E07 (2)).
 *
 * Mapping: one page-rounded anonymous window region named "[vdso]"
 * (guest prot r-x; host prot drops the exec bit per i686_host_prot —
 * the window is data, translated code lives outside it).  Placement is
 * the shelf between the guest mmap ceiling (0xdf000000, rt32_vm.c
 * never allocates above it) and the initial guest stack mapping
 * (0xdf800000..0xe0000000, rt32_stack32.c): a zone ordinary guest
 * mmap2 calls never hand out, mirroring the kernel's practice of
 * keeping the vDSO out of the regular mmap area.  The shelf is scanned
 * top-down for a slot free of recorded regions.
 */

#define _GNU_SOURCE
#include "vdso.h"

#include <stdio.h>
#include <string.h>
#include <sys/mman.h>

#include "rt32/rt32.h"

/* Generated by tools/mkvdso32.sh (the committed vDSO artifact). */
extern const unsigned char i686_vdso32_blob[];
extern const unsigned long i686_vdso32_blob_size;

/* Placement shelf [bottom, top): above the guest mmap ceiling, below
 * the initial stack mapping. */
#define VDSO_SHELF_BOTTOM 0xDF000000U
#define VDSO_SHELF_TOP    0xDF800000U

/* ELF32 definitions (local, mirroring src/rt32/rt32_elf32.c). */
#define EI_NIDENT   16U
#define ELFCLASS32  1U
#define ELFDATA2LSB 1U
#define ET_DYN      3U
#define EM_386      3U

#define PT_LOAD    1U
#define PT_DYNAMIC 2U

#define DT_NULL   0
#define DT_HASH   4
#define DT_STRTAB 5
#define DT_SYMTAB 6
#define DT_STRSZ  10
#define DT_SYMENT 11

#define STB_GLOBAL 1U
#define STB_WEAK   2U

#define VDSO_MAX_PHDRS 64U
#define VDSO_MAX_DYNSYM 4096U

typedef struct elf32_ehdr {
    uint8_t  e_ident[EI_NIDENT];
    uint16_t e_type;
    uint16_t e_machine;
    uint32_t e_version;
    uint32_t e_entry;
    uint32_t e_phoff;
    uint32_t e_shoff;
    uint32_t e_flags;
    uint16_t e_ehsize;
    uint16_t e_phentsize;
    uint16_t e_phnum;
    uint16_t e_shentsize;
    uint16_t e_shnum;
    uint16_t e_shstrndx;
} elf32_ehdr_t;

typedef struct elf32_phdr {
    uint32_t p_type;
    uint32_t p_offset;
    uint32_t p_vaddr;
    uint32_t p_paddr;
    uint32_t p_filesz;
    uint32_t p_memsz;
    uint32_t p_flags;
    uint32_t p_align;
} elf32_phdr_t;

typedef struct elf32_dyn {
    int32_t  d_tag;
    uint32_t d_val;
} elf32_dyn_t;

typedef struct elf32_sym {
    uint32_t st_name;
    uint32_t st_value;
    uint32_t st_size;
    uint8_t  st_info;
    uint8_t  st_other;
    uint16_t st_shndx;
} elf32_sym_t;

/* One-time parse result (the blob is const; identical for every ctx). */
typedef struct vdso_info {
    elf32_phdr_t phdrs[VDSO_MAX_PHDRS];
    uint16_t     phnum;
    uint32_t     min_page;     /* page-down of the lowest PT_LOAD vaddr */
    uint32_t     span;         /* page-rounded extent of all PT_LOADs   */
    uint32_t     vsyscall_off; /* __kernel_vsyscall vaddr - min_page    */
} vdso_info_t;

static vdso_info_t g_vdso;
static int         g_vdso_state; /* 0 = unparsed, 1 = ok, -1 = invalid */

static size_t vdso_blob_len(void)
{
    return (size_t)i686_vdso32_blob_size;
}

/* Bounds-checked read out of the (byte-aligned, const) blob. */
static int vdso_blob_read(size_t off, void *dst, size_t len)
{
    size_t blen = vdso_blob_len();
    if (off > blen || len > blen - off) {
        return -1;
    }
    memcpy(dst, i686_vdso32_blob + off, len);
    return 0;
}

/* Image vaddr -> blob offset, via the PT_LOAD covering it. */
static int vdso_vaddr_to_off(const elf32_phdr_t *phdrs, uint16_t phnum,
                             uint32_t vaddr, size_t *out_off)
{
    for (uint16_t i = 0U; i < phnum; i++) {
        if (phdrs[i].p_type == PT_LOAD && phdrs[i].p_filesz > 0U &&
            vaddr >= phdrs[i].p_vaddr &&
            vaddr - phdrs[i].p_vaddr < phdrs[i].p_filesz) {
            *out_off = (size_t)phdrs[i].p_offset + (size_t)(vaddr - phdrs[i].p_vaddr);
            return 0;
        }
    }
    return -1;
}

static int vdso_parse(vdso_info_t *info)
{
    size_t blen = vdso_blob_len();

    elf32_ehdr_t ehdr;
    if (blen < sizeof(ehdr) || vdso_blob_read(0U, &ehdr, sizeof(ehdr)) != 0) {
        return -1;
    }
    if (ehdr.e_ident[0] != 0x7fU || ehdr.e_ident[1] != 'E' ||
        ehdr.e_ident[2] != 'L'  || ehdr.e_ident[3] != 'F' ||
        ehdr.e_ident[4] != ELFCLASS32 || ehdr.e_ident[5] != ELFDATA2LSB ||
        ehdr.e_machine != EM_386 || ehdr.e_type != ET_DYN) {
        return -1;
    }
    if (ehdr.e_phentsize != sizeof(elf32_phdr_t) ||
        ehdr.e_phnum == 0U || (uint32_t)ehdr.e_phnum > VDSO_MAX_PHDRS) {
        return -1;
    }

    memset(info, 0, sizeof(*info));
    info->phnum = ehdr.e_phnum;
    if (vdso_blob_read((size_t)ehdr.e_phoff, info->phdrs,
                       (size_t)ehdr.e_phnum * sizeof(elf32_phdr_t)) != 0) {
        return -1;
    }

    uint32_t min_vaddr = 0xFFFFFFFFU;
    uint32_t max_end   = 0U;
    bool     have_load = false;
    for (uint16_t i = 0U; i < info->phnum; i++) {
        const elf32_phdr_t *ph = &info->phdrs[i];
        if (ph->p_type != PT_LOAD) {
            continue;
        }
        if (ph->p_filesz > ph->p_memsz ||
            (uint64_t)ph->p_vaddr + (uint64_t)ph->p_memsz > 0xFFFFF000ULL ||
            (size_t)ph->p_offset > blen ||
            (size_t)ph->p_filesz > blen - (size_t)ph->p_offset) {
            return -1;
        }
        if (ph->p_memsz == 0U) {
            continue;
        }
        if (ph->p_vaddr < min_vaddr) {
            min_vaddr = ph->p_vaddr;
        }
        if ((uint64_t)ph->p_vaddr + (uint64_t)ph->p_memsz > (uint64_t)max_end) {
            max_end = ph->p_vaddr + ph->p_memsz;
        }
        have_load = true;
    }
    if (!have_load) {
        return -1;
    }

    info->min_page = i686_page_down(min_vaddr);
    info->span     = i686_page_up(max_end) - info->min_page;
    if (info->span == 0U || info->span > VDSO_SHELF_TOP - VDSO_SHELF_BOTTOM) {
        return -1;
    }

    /* Dynamic tags: SYMTAB/STRTAB (+HASH for the entry count). */
    const elf32_phdr_t *dyn_ph = NULL;
    for (uint16_t i = 0U; i < info->phnum; i++) {
        if (info->phdrs[i].p_type == PT_DYNAMIC) {
            dyn_ph = &info->phdrs[i];
            break;
        }
    }
    if (dyn_ph == NULL) {
        return -1;
    }
    size_t dyn_off = 0U;
    if (vdso_vaddr_to_off(info->phdrs, info->phnum, dyn_ph->p_vaddr, &dyn_off) != 0) {
        return -1;
    }

    uint32_t hash_va = 0U, sym_va = 0U, str_va = 0U, strsz = 0U;
    bool have_sym = false, have_str = false;
    for (uint32_t i = 0U; i < 512U; i++) {
        elf32_dyn_t dyn;
        if (vdso_blob_read(dyn_off + (size_t)i * sizeof(elf32_dyn_t),
                           &dyn, sizeof(dyn)) != 0) {
            return -1;
        }
        if (dyn.d_tag == DT_NULL) {
            break;
        }
        switch (dyn.d_tag) {
        case DT_HASH:
            hash_va = dyn.d_val;
            break;
        case DT_SYMTAB:
            sym_va  = dyn.d_val;
            have_sym = true;
            break;
        case DT_STRTAB:
            str_va  = dyn.d_val;
            have_str = true;
            break;
        case DT_STRSZ:
            strsz = dyn.d_val;
            break;
        case DT_SYMENT:
            if (dyn.d_val != sizeof(elf32_sym_t)) {
                return -1;
            }
            break;
        default:
            break;
        }
    }
    if (!have_sym || !have_str || strsz == 0U) {
        return -1;
    }

    size_t sym_off = 0U, str_off = 0U;
    if (vdso_vaddr_to_off(info->phdrs, info->phnum, sym_va, &sym_off) != 0 ||
        vdso_vaddr_to_off(info->phdrs, info->phnum, str_va, &str_off) != 0 ||
        (size_t)strsz > blen - str_off) {
        return -1;
    }

    /* Number of dynsym entries: nchain from DT_HASH; without DT_HASH,
     * the .dynsym section runs up against .dynstr (linker layout). */
    uint32_t nsyms = 0U;
    if (hash_va != 0U) {
        size_t hash_off = 0U;
        uint32_t nchain = 0U;
        if (vdso_vaddr_to_off(info->phdrs, info->phnum, hash_va, &hash_off) != 0 ||
            vdso_blob_read(hash_off + 4U, &nchain, sizeof(nchain)) != 0 ||
            nchain == 0U || nchain > VDSO_MAX_DYNSYM) {
            return -1;
        }
        nsyms = nchain;
    } else {
        if (str_off <= sym_off) {
            return -1;
        }
        nsyms = (uint32_t)((str_off - sym_off) / sizeof(elf32_sym_t));
    }
    if ((size_t)nsyms > (blen - sym_off) / sizeof(elf32_sym_t)) {
        return -1;
    }

    /* Resolve __kernel_vsyscall; the image contract requires
     * e_entry == its value (E07: AT_SYSINFO == vdso_base + e_entry). */
    for (uint32_t i = 0U; i < nsyms; i++) {
        elf32_sym_t sym;
        if (vdso_blob_read(sym_off + (size_t)i * sizeof(elf32_sym_t),
                           &sym, sizeof(sym)) != 0) {
            return -1;
        }
        uint32_t bind = (uint32_t)(sym.st_info >> 4);
        if (bind != STB_GLOBAL && bind != STB_WEAK) {
            continue;
        }
        if (sym.st_name >= strsz) {
            continue;
        }
        const unsigned char *name =
            i686_vdso32_blob + str_off + (size_t)sym.st_name;
        size_t name_room = (size_t)strsz - (size_t)sym.st_name;
        if (memchr(name, '\0', name_room) == NULL) {
            continue;
        }
        if (strcmp((const char *)name, "__kernel_vsyscall") == 0) {
            if (sym.st_value < info->min_page ||
                sym.st_value - info->min_page >= info->span ||
                ehdr.e_entry != sym.st_value) {
                return -1;
            }
            info->vsyscall_off = sym.st_value - info->min_page;
            return 0;
        }
    }
    return -1;
}

static bool vdso_range_overlaps(const i686_ctx_t *ctx, uint32_t start, uint32_t end)
{
    for (size_t i = 0U; i < ctx->region_count; i++) {
        if (start < ctx->regions[i].end && end > ctx->regions[i].start) {
            return true;
        }
    }
    return false;
}

uint32_t i686_vdso_map(i686_ctx_t *ctx)
{
    if (ctx == NULL) {
        return 0U;
    }
    if (ctx->vdso_base != 0U) {
        return ctx->vdso_base; /* idempotent */
    }

    if (g_vdso_state == 0) {
        g_vdso_state = (vdso_parse(&g_vdso) == 0) ? 1 : -1;
    }
    if (g_vdso_state < 0) {
        fprintf(stderr, "i686rt: [vdso]: embedded image failed validation\n");
        return 0U;
    }

    uint32_t span = g_vdso.span;
    uint32_t base = 0U;
    uint32_t cand = VDSO_SHELF_TOP - span;
    for (;;) {
        if (!vdso_range_overlaps(ctx, cand, cand + span)) {
            base = cand;
            break;
        }
        if (cand < VDSO_SHELF_BOTTOM + I686_PAGE_SIZE) {
            break;
        }
        cand -= I686_PAGE_SIZE;
    }
    if (base == 0U) {
        fprintf(stderr, "i686rt: [vdso]: no free slot in [0x%x, 0x%x)\n",
                VDSO_SHELF_BOTTOM, VDSO_SHELF_TOP);
        return 0U;
    }

    void *host = i686_guest_ptr(ctx, base);
    void *res  = mmap(host, span, PROT_READ | PROT_WRITE,
                      MAP_PRIVATE | MAP_ANONYMOUS | MAP_FIXED, -1, 0);
    if (res == MAP_FAILED) {
        fprintf(stderr, "i686rt: [vdso]: mmap of [0x%x, 0x%x) failed\n",
                base, base + span);
        return 0U;
    }

    for (uint16_t i = 0U; i < g_vdso.phnum; i++) {
        const elf32_phdr_t *ph = &g_vdso.phdrs[i];
        if (ph->p_type != PT_LOAD || ph->p_filesz == 0U) {
            continue;
        }
        uint32_t seg_va = base + (ph->p_vaddr - g_vdso.min_page);
        memcpy(i686_guest_ptr(ctx, seg_va),
               i686_vdso32_blob + (size_t)ph->p_offset,
               (size_t)ph->p_filesz);
        if (ph->p_memsz > ph->p_filesz) {
            memset(i686_guest_ptr(ctx, seg_va + ph->p_filesz), 0,
                   (size_t)(ph->p_memsz - ph->p_filesz));
        }
    }

    /* Guest view r-x like the kernel's vdso mapping; host prot drops
     * the exec bit (window is data, D11). */
    if (mprotect(host, span, i686_host_prot(ctx, PROT_READ | PROT_EXEC)) != 0) {
        fprintf(stderr, "i686rt: [vdso]: mprotect of [0x%x, 0x%x) failed\n",
                base, base + span);
        (void)mprotect(host, span, PROT_NONE);
        return 0U;
    }
    if (rt32_vm_record_region(ctx, base, base + span,
                              (uint32_t)(PROT_READ | PROT_EXEC), 0x22U,
                              "[vdso]") != 0) {
        fprintf(stderr, "i686rt: [vdso]: failed to record region\n");
        (void)mprotect(host, span, PROT_NONE);
        return 0U;
    }

    ctx->vdso_base = base;
    return base;
}

uint32_t i686_vdso_vsyscall_addr(const i686_ctx_t *ctx)
{
    if (ctx == NULL || ctx->vdso_base == 0U || g_vdso_state != 1) {
        return 0U;
    }
    return ctx->vdso_base + g_vdso.vsyscall_off;
}
